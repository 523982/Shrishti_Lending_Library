-- Supabase/PostgreSQL schema for Shrishti Lending Library.
-- Run this in Supabase SQL Editor before pointing the Spring Boot app to Supabase.

create table if not exists book_status (
    status_id bigint primary key,
    description varchar(50) not null unique
);

insert into book_status (status_id, description) values
    (1, 'AVAILABLE'),
    (2, 'UNAVAILABLE'),
    (3, 'SOLD'),
    (4, 'LOST_DAMAGED'),
    (5, 'TO_BE_SOLD'),
    (6, 'OBSOLETE')
on conflict (status_id) do update
set description = excluded.description;

create table if not exists communities (
    community_id bigint primary key,
    community_name varchar(255) not null unique
);

create table if not exists offers (
    offer_id bigint generated by default as identity primary key,
    offer_name varchar(255) not null,
    community_id bigint not null references communities(community_id),
    offer_type varchar(20) not null check (offer_type in ('BUNDLE', 'PERCENT')),
    start_date date not null,
    end_date date not null,
    discount_percent numeric(5, 2),
    bundle_book_count integer,
    bundle_price numeric(10, 2),
    bundle_duration_days integer,
    is_active boolean not null default true,
    created_at timestamp with time zone not null default now()
);

alter table communities
add column if not exists active_offer_id bigint references offers(offer_id);

alter table communities
add column if not exists is_offer_active boolean not null default false;

create table if not exists login (
    username varchar(64) primary key,
    pw varchar(255) not null,
    role varchar(30) not null check (lower(role) in ('admin', 'guest'))
);

